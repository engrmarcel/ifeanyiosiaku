import { cacheLife } from "next/cache";
import { codeToHtml, type ShikiTransformer } from "shiki";
import { cn } from "@/lib/cn";
import { CopyButton } from "./CopyButton";

const THEME = "github-dark-default";

/**
 * Server-rendered syntax highlighting (no JavaScript sent to the browser for highlighting).
 * Code is only ever displayed, never executed. Results are cached per code + options.
 */
async function highlight(code: string, language: string, highlightLines: number[], lineNumbers: boolean): Promise<string> {
  "use cache";
  cacheLife("max");

  const marked = new Set(highlightLines);
  const transformer: ShikiTransformer = {
    pre(node) {
      this.addClassToHast(node, cn("io-code", lineNumbers && "io-code--numbered"));
      delete node.properties.style; // colours come from our design tokens, not inline styles
    },
    line(node, line) {
      node.properties["data-line"] = line;
      if (marked.has(line)) this.addClassToHast(node, "io-code-line--highlight");
    },
  };

  try {
    return await codeToHtml(code, { lang: language, theme: THEME, transformers: [transformer] });
  } catch {
    // Unknown language: show as plain text rather than failing the page.
    return codeToHtml(code, { lang: "plaintext", theme: THEME, transformers: [transformer] });
  }
}

export async function HighlightedCode({
  code,
  language,
  title,
  lineNumbers = true,
  copyButton = true,
  highlightLines = [],
  annotations = [],
  caption,
}: {
  code: string;
  language: string;
  title?: string | null;
  lineNumbers?: boolean;
  copyButton?: boolean;
  highlightLines?: number[];
  annotations?: { line: number; note: string }[];
  caption?: string | null;
}) {
  const html = await highlight(code, language, highlightLines, lineNumbers);

  return (
    <figure className="overflow-hidden rounded-lg border border-border bg-[#0d1117]">
      <div className="flex items-center justify-between gap-3 border-b border-border px-4 py-2">
        <span className="truncate font-mono text-xs text-muted">{title || language}</span>
        <div className="flex items-center gap-3">
          <span className="font-mono text-[10px] tracking-wider text-muted/70 uppercase">{language}</span>
          {copyButton && <CopyButton text={code} />}
        </div>
      </div>
      {/* Shiki output: generated by us from plain text, so it contains no user HTML. */}
      <div className="overflow-x-auto text-[13px] leading-6" dangerouslySetInnerHTML={{ __html: html }} />
      {annotations.length > 0 && (
        <ol className="space-y-1 border-t border-border px-4 py-3 text-sm text-muted">
          {annotations.map((a) => (
            <li key={`${a.line}-${a.note}`}>
              <span className="mr-2 font-mono text-xs text-accent">L{a.line}</span>
              {a.note}
            </li>
          ))}
        </ol>
      )}
      {caption && <figcaption className="border-t border-border px-4 py-2 text-xs text-muted">{caption}</figcaption>}
    </figure>
  );
}
